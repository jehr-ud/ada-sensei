"""Exam assessment report generation (RQ-EXM-024, RQ-EXM-029).

The report is the instructor-facing artifact, so it must be reconstructable: the
calculation table shows every dimension, its weight, its score and its
contribution, plus the denominator actually used. The grade is always labelled as
a suggested grade generated by ADA Sensei, and nothing the LLM said enters the
arithmetic.
"""

from __future__ import annotations

from pathlib import Path

from ..urns import URN
from .models import SUGGESTED_GRADE_LABEL, ExamDefinition, ExamResult
from .pdf import SimplePdfWriter

#: Report sections, in the order the spec lists them.
SECTIONS = (
    "Exam identification",
    "Student",
    "Project",
    "Exam attempt",
    "Timing",
    "Rubric",
    "Calculation",
    "Executive assessment",
    "Functional requirements",
    "Test evidence",
    "Code quality",
    "Clean architecture",
    "Android practices",
    "Exam process",
    "Architecture",
    "Strengths",
    "Weaknesses",
    "Recommendations",
    "Detailed evidence",
    "Limitations",
    "Suggested grade",
    "Methodology",
)


class ExamReportGenerator:
    """Renders an ``ExamResult`` into a detailed, evidence-linked PDF."""

    def __init__(self, output_dir: str | Path) -> None:
        #: Reports live in the ADA Sensei data/output location, never in the
        #: student's source tree (spec.md §Project docs directory).
        self.output_dir = Path(output_dir)

    def default_path(self, result: ExamResult) -> Path:
        return self.output_dir / "exams" / f"{_slug(result.exam_attempt_id)}.pdf"

    def generate(
        self,
        result: ExamResult,
        definition: ExamDefinition | None = None,
        path: str | Path | None = None,
    ) -> tuple[Path, str]:
        """Write the PDF and return ``(path, report_id)``."""
        target = Path(path) if path is not None else self.default_path(result)
        target.parent.mkdir(parents=True, exist_ok=True)
        report_id = result.report_id or URN.make("exam_report")
        payload = self._render(result, definition, report_id)
        target.write_bytes(payload)
        return target, report_id

    @staticmethod
    def _language_line(locale: str | None) -> str:
        """Report language line from the attempt snapshot (RQ-LNG-013).

        ``Language: Español (es-CO)`` when known, else ``""`` (legacy
        records without a snapshot render as before).
        """
        if not locale:
            return ""
        from ..locale.models import LOCALE_LABELS

        label = LOCALE_LABELS.get(locale, locale)
        return f"Language: {label} ({locale})"

    def render_text(self, result: ExamResult) -> str:
        """A plain-text twin of the PDF.

        Same sections and same body text as ``_render``, without the PDF
        encoding, so report content is assertable without parsing bytes. Not on
        any production path: the CLI shows its own summary and the PDF is the
        deliverable.
        """
        lines: list[str] = [
            f"Exam: {result.exam_title or result.exam_id}",
            f"Student: {result.student_id}",
            f"Project: {result.project_id}",
            f"Exam attempt: {result.exam_attempt_id}",
        ]
        language = self._language_line(result.locale)
        if language:
            lines.append(language)
        for heading, body in self._sections(result):
            lines += ["", f"## {heading}", "", body]
        lines += ["", f"_{result.grade_disclosure}_", ""]
        return "\n".join(lines).strip() + "\n"

    # -- rendering --------------------------------------------------------

    def _render(
        self,
        result: ExamResult,
        definition: ExamDefinition | None,
        report_id: str,
    ) -> bytes:
        writer = SimplePdfWriter()
        self._cover(writer, result, report_id, definition)
        for heading, body in self._sections(result):
            writer.heading(heading, 2)
            for kind, text in _blocks(body):
                if kind == "p":
                    writer.paragraph(text)
                else:
                    writer.bullet(text)
        return writer.build()

    def _cover(
        self,
        writer: SimplePdfWriter,
        result: ExamResult,
        report_id: str,
        definition: ExamDefinition | None,
    ) -> None:
        writer.paragraph("ADA Sensei", size=9.0)
        writer.heading("Exam assessment report", 1)
        writer.key_value("Exam", result.exam_title or result.exam_id or "(unknown)")
        writer.key_value("Student", result.student_id or "(unknown)")
        writer.key_value("Project", result.project_id or "(unknown)")
        writer.key_value("Exam attempt", result.exam_attempt_id or "(unknown)")
        writer.key_value("Report id", report_id)
        language = self._language_line(result.locale)
        if language:
            _, language_value = language.split(": ", 1)
            writer.key_value("Language", language_value)
        if definition is not None:
            writer.key_value("Statement source", definition.statement_source)
        if result.rubric_ref:
            writer.key_value("Rubric", result.rubric_ref)
        writer.paragraph(result.grade_disclosure, size=11.0)
        writer.paragraph(
            "This report is an assessment aid for the instructor. It is not an "
            "authoritative institutional grade, and it is produced by automated "
            "analysis of the project plus a structured language-model "
            "interpretation bounded by the evidence listed below.",
            size=9.0,
        )
        self._calculation_table(writer, result)
        writer.page_break()

    def _calculation_table(self, writer: SimplePdfWriter, result: ExamResult) -> None:
        calculation = result.score_calculation
        if calculation is None:
            writer.paragraph("No calculation is available for this result.")
            return
        writer.heading("Score calculation", 2)
        rows = [["Dimension", "Weight", "Score", "Contribution"]]
        for line in calculation.lines:
            rows.append(
                [
                    line.dimension,
                    f"{line.weight * 100:.0f}%",
                    _score_text(line.score, line.not_evaluated_reason),
                    _contribution_text(line.contribution),
                ]
            )
        rows.append(
            [
                "Denominator (evaluated weight)",
                "",
                "",
                f"{calculation.weight_denominator:.4f}",
            ]
        )
        rows.append(
            ["Percentage (0-100)", "", "", _score_text(calculation.percentage, None)]
        )
        rows.append(
            [
                f"Raw score (0-{calculation.max_raw_score})",
                "",
                "",
                str(calculation.raw_score_50)
                if calculation.raw_score_50 is not None
                else "not evaluated",
            ]
        )
        rows.append(
            [
                f"Suggested grade (1.0-{calculation.max_grade})",
                "",
                "",
                str(calculation.suggested_grade)
                if calculation.suggested_grade is not None
                else "not evaluated",
            ]
        )
        writer.table(rows, [3.2, 1.0, 1.6, 1.4])

    def _sections(self, result: ExamResult) -> list[tuple[str, str]]:
        """(heading, body) pairs; body uses blank-line-separated blocks."""
        return [
            ("Timing", self._timing(result)),
            ("Executive assessment", result.feedback or "No executive assessment."),
            ("Functional requirements", self._requirements(result)),
            ("Test evidence", self._dimension(result, "tests", "unit_test")),
            ("Code quality", self._dimension(result, "code_quality", "detekt")),
            (
                "Clean architecture",
                self._dimension(result, "clean_architecture", "structure"),
            ),
            (
                "Android practices",
                self._dimension(result, "android_practices", "android_lint"),
            ),
            ("Exam process", self._process(result)),
            ("Architecture", self._architecture(result)),
            ("Strengths", _bulleted(result.strengths, "No strengths identified.")),
            ("Weaknesses", _bulleted(result.weaknesses, "No weaknesses identified.")),
            (
                "Recommendations",
                _bulleted(result.recommendations, "No recommendations produced."),
            ),
            ("Detailed evidence", self._evidence(result)),
            ("Limitations", self._limitations(result)),
            (
                "Suggested grade",
                f"{result.grade_disclosure}\n\n"
                f"Raw score: {_score_text(result.raw_score_50, None)} of "
                f"{_max_raw(result)}\n"
                f"Suggested grade: "
                f"{_or_not_evaluated(result.suggested_grade)}"
                f" of 5.0",
            ),
            ("Methodology", self._methodology(result)),
        ]

    # -- section bodies ---------------------------------------------------

    def _timing(self, result: ExamResult) -> str:
        return "\n".join(
            [
                f"Started: {_timestamp(result.started_at)}",
                f"Finished: {_timestamp(result.finished_at)}",
                f"Duration: {_duration(result.duration_seconds)}"
                + (
                    f" (allowed {_duration(result.allowed_duration_seconds)}, "
                    f"overtime {_duration(result.overtime_seconds)})"
                    if result.allowed_duration_seconds is not None
                    else " (no allowed duration defined)"
                ),
                f"/ask count: {result.ask_count}"
                + (
                    f" of {result.allowed_ask_count} allowed"
                    if result.allowed_ask_count is not None
                    else " (no ask limit defined)"
                ),
            ]
        )

    def _requirements(self, result: ExamResult) -> str:
        criteria = [
            c for c in result.criteria if c.dimension == "functional_requirements"
        ]
        if not criteria:
            return (
                "The instructor statement exposed no machine-readable functional "
                "requirements, so this dimension is not evaluated."
            )
        return "\n".join(
            f"{c.requirement_id} [{_score_text(c.score, c.not_evaluated_reason)}] "
            f"weight {c.weight:.3f}: {c.note or '(no description)'}"
            + (f"  evidence: {', '.join(c.evidence_refs)}" if c.evidence_refs else "")
            for c in criteria
        )

    def _dimension(self, result: ExamResult, dimension: str, group: str) -> str:
        score = result.dimension_scores.get(dimension)
        findings = [e for e in result.evidence if e.type == group or e.source == group]
        header = f"Score: {_score_text(score, None)}"
        if not findings:
            return f"{header}\nNo {group} evidence was collected."
        lines = [header]
        for item in findings[:40]:
            lines.append(
                f"{item.id} [{item.severity or item.status}] {item.file or ''} "
                f"{item.message}".strip()
            )
        return "\n".join(lines)

    def _process(self, result: ExamResult) -> str:
        metrics = result.process_metrics
        if metrics is None:
            return "No exam process metrics were recorded."
        duration = (
            f"{metrics.duration_score} "
            f"(ratio {metrics.duration_seconds}/{metrics.allowed_duration_seconds})"
            if metrics.duration_score is not None
            else f"not evaluated ({_reason(metrics.duration_reason)})"
        )
        asks = (
            f"{metrics.ask_usage_score} "
            f"({metrics.ask_count}/{metrics.allowed_ask_count})"
            if metrics.ask_usage_score is not None
            else f"not evaluated ({_reason(metrics.ask_usage_reason)})"
        )
        return "\n".join(
            [
                f"Duration score: {duration}",
                f"/ask usage score: {asks}",
                f"Overtime: {_duration(metrics.overtime_seconds)}",
                "Ask usage measures use of the tutor, not correctness or honesty.",
            ]
        )

    def _architecture(self, result: ExamResult) -> str:
        report = result.architecture_report
        if report is None:
            return "No architecture analysis was produced."
        lines = [report.narrative] if report.narrative else []
        for kind, title in (
            ("observed", "Observed in the project"),
            ("documented", "Documented by the student"),
            ("inferred", "Inferred interpretation"),
        ):
            claims = report.by_kind(kind)
            if not claims:
                continue
            lines.append(f"{title}:")
            lines += [
                f"{c.claim} [{', '.join(c.evidence_refs) or 'no reference'}]"
                for c in claims
            ]
        if report.modules:
            lines.append("Modules: " + ", ".join(report.modules))
        if report.packages:
            lines.append("Packages: " + ", ".join(report.packages))
        if report.unsupported_claims:
            lines.append("Claims excluded as unsupported:")
            lines += [f"{c.claim} ({c.reason})" for c in report.unsupported_claims]
        return "\n".join(lines) or "No architecture claims could be grounded."

    def _evidence(self, result: ExamResult) -> str:
        if not result.evidence:
            return "No evidence was collected."
        return "\n".join(
            f"{e.id} [{e.source}/{e.type}/{e.status}] "
            f"severity={e.severity or '-'} {e.file or ''} {e.message}".strip()
            for e in result.evidence
        )

    def _limitations(self, result: ExamResult) -> str:
        lines = list(result.limitations)
        for claim in result.unsupported_claims:
            lines.append(f"unsupported claim excluded: {claim.claim} ({claim.reason})")
        if result.architecture_report is not None:
            for claim in result.architecture_report.unsupported_claims:
                lines.append(
                    f"unsupported architecture claim excluded: {claim.claim} "
                    f"({claim.reason})"
                )
        return "\n".join(lines) or "No limitations were recorded."

    def _methodology(self, result: ExamResult) -> str:
        return "\n".join(
            [
                "Functional, tests, code-quality, clean-architecture, "
                "Android-practice and exam-process scores are computed "
                "deterministically from collected evidence and the exam rubric.",
                "The raw score is "
                "50 x sum(weight x score / 4) / sum(weight of evaluated "
                "dimensions), rounded to the nearest integer.",
                "The suggested grade is round(1.0 + (raw score / 50) x 4.0, 1), "
                "giving 1.0 at 0 and 5.0 at 50.",
                "Dimensions without sufficient evidence are marked not evaluated "
                "and removed from the denominator; they never count as a pass.",
                "Qualitative text is a structured language-model interpretation "
                "grounded in the evidence ids listed in this report. Claims that "
                "could not be grounded are listed under Limitations.",
                f"Suggested grade: {SUGGESTED_GRADE_LABEL}.",
            ]
        )


def _blocks(body: str) -> list[tuple[str, str]]:
    """Split a section body into paragraphs and bullets."""
    out: list[tuple[str, str]] = []
    for chunk in body.split("\n"):
        text = chunk.strip()
        if not text:
            continue
        kind = "li" if text.startswith("- ") else "p"
        out.append((kind, text[2:] if kind == "li" else text))
    return out


def _bulleted(items: list[str], empty: str) -> str:
    return "\n".join(f"- {item}" for item in items) if items else empty


def _score_text(score: float | int | None, reason) -> str:
    if score is None:
        return f"not evaluated ({_reason(reason)})"
    return f"{score:g}"


def _or_not_evaluated(value: object) -> str:
    return "not evaluated" if value is None else str(value)


def _contribution_text(contribution: float | None) -> str:
    return "-" if contribution is None else f"{contribution:.3f}"


def _max_raw(result: ExamResult) -> int:
    calculation = result.score_calculation
    return calculation.max_raw_score if calculation is not None else 50


def _reason(reason) -> str:
    return getattr(reason, "value", None) or "no_evidence"


def _timestamp(value) -> str:
    return value.isoformat() if value is not None else "(not recorded)"


def _duration(seconds: int | None) -> str:
    if seconds is None:
        return "not recorded"
    minutes, rest = divmod(int(seconds), 60)
    return f"{minutes}m {rest}s" if minutes else f"{rest}s"


def _slug(value: str | None) -> str:
    return (value or "unknown").rsplit("://", 1)[-1]


__all__ = ["SECTIONS", "ExamReportGenerator"]
