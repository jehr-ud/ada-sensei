"""Exam domain models (``007-examine``).

Identity is the point of this module: ``student_id``, ``project_id``,
``exam_id``, ``attempt_id`` and ``exam_attempt_id`` are five separate fields
(RQ-EXM-001) and nothing here infers one from another. Duration and ask counts
live on the attempt and are only ever written from application events
(RQ-EXM-006/007/031), never from model output.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

from ..models import (
    EvaluationCriterion,
    EvaluationResult,
    Evidence,
    NotEvaluatedReason,
    Timestamps,
    UnsupportedClaim,
)
from ..urns import URN

#: Rubric the exam falls back to when a definition does not override it.
DEFAULT_EXAM_RUBRIC_REF = "exam-default:v1"

#: The exact wording the spec requires on the report (RQ-EXM-029).
SUGGESTED_GRADE_LABEL = "Suggested grade — generated by ADA Sensei"

#: Fields an exam attempt may still change after completion. Everything else is
#: frozen by the exam store once the attempt is completed (RQ-EXM-004).
ADMINISTRATIVE_FIELDS = frozenset({"administrative_metadata"})


class ExamStatus(StrEnum):
    """Lifecycle states (design.md §Exam lifecycle state machine)."""

    created = "created"
    active = "active"
    evaluating = "evaluating"
    completed = "completed"


class ExamEventType(StrEnum):
    """Application events the exam attempt log understands."""

    exam_started = "EXAM_STARTED"
    ask_started = "ASK_STARTED"
    ask_completed = "ASK_COMPLETED"
    ask_failed = "ASK_FAILED"
    ask_cancelled = "ASK_CANCELLED"
    exam_finish_requested = "EXAM_FINISH_REQUESTED"
    exam_finished = "EXAM_FINISHED"
    evaluation_started = "EVALUATION_STARTED"
    evaluation_completed = "EVALUATION_COMPLETED"


#: Only a successful ask counts against the exam allowance (RQ-EXM-005).
ASK_SUCCESS_EVENTS = (ExamEventType.ask_completed,)

#: Ask events that are recorded but never counted (spec.md §Ask tracking).
ASK_NON_COUNTING_EVENTS = (ExamEventType.ask_failed, ExamEventType.ask_cancelled)


class ExamError(Exception):
    """Base for every exam workflow error the CLI maps to a user message."""


class ExamDefinitionError(ExamError):
    """The instructor exam statement could not be resolved."""


class ExamStateError(ExamError):
    """An illegal lifecycle transition was attempted."""


class ExamAttemptImmutableError(ExamError):
    """A completed exam attempt was modified (RQ-EXM-004)."""


class ExamAttemptNotFoundError(ExamError):
    """No exam attempt is active for the current session."""


class StatementFormat(StrEnum):  # type: ignore[misc]
    """Instructor statement containers accepted by the loader (RQ-EXM-002)."""

    markdown = "markdown"
    json = "json"
    pdf = "pdf"


class DocumentationRules(BaseModel):
    """Which student-authored files count as exam documentation (RQ-EXM-008)."""

    model_config = ConfigDict(frozen=True)

    #: Globs, relative to the project root, the exam accepts as documentation.
    accepted_globs: tuple[str, ...] = ("docs/exam/**/*.md", "docs/exam/**/*.txt")
    #: Optional files an instructor requires for a complete submission.
    required_files: tuple[str, ...] = ()
    #: Documentation may not assert behaviour that project evidence contradicts
    #: (spec.md §Exam definition and documentation).
    documentation_is_advisory: bool = True


class ExamRequirement(BaseModel):
    """One instructor requirement with a stable id and declared weight."""

    requirement_id: str = Field(default_factory=lambda: URN.make("exam_req"))
    description: str
    dimension: str = "functional_requirements"
    weight: float = 1.0
    evidence_expectations: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _weight_non_negative(self) -> ExamRequirement:
        if self.weight < 0:
            raise ValueError(
                f"requirement {self.requirement_id!r} weight must be >= 0"
            )
        return self


class ExamDefinition(BaseModel):
    """The authoritative exam statement, resolved from an instructor source."""

    exam_id: str = Field(default_factory=lambda: URN.make("exam"))
    title: str = ""
    version: str = "v1"
    statement_format: StatementFormat = StatementFormat.markdown
    #: Where the statement came from (path, or ``inline`` for embedded text).
    statement_source: str = "inline"
    #: The original statement, preserved verbatim (spec.md §PDF preservation).
    original_statement: str = ""
    original_source_path: str | None = None
    requirements: list[ExamRequirement] = Field(default_factory=list)
    allowed_duration_seconds: int | None = None
    allowed_ask_count: int | None = None
    #: Versioned rubric the exam is scored with (design.md §Core models).
    rubric_ref: str = DEFAULT_EXAM_RUBRIC_REF
    documentation_rules: DocumentationRules = DocumentationRules()
    #: Anything the loader could not normalize, surfaced rather than dropped.
    limitations: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _functional_weights_sum_to_one(self) -> ExamDefinition:
        functional = [
            r for r in self.requirements
            if r.dimension == "functional_requirements"
        ]
        if not functional:
            return self
        total = sum(r.weight for r in functional)
        if abs(total - 1.0) > 1e-6:
            raise ValueError(
                "functional requirement weights must sum to 1.0, got "
                f"{total} ({[r.requirement_id for r in functional]})"
            )
        ids = [r.requirement_id for r in self.requirements]
        if len(ids) != len(set(ids)):
            raise ValueError(f"duplicate exam requirement ids: {ids}")
        return self

    def requirement(self, requirement_id: str) -> ExamRequirement:
        for req in self.requirements:
            if req.requirement_id == requirement_id:
                return req
        raise KeyError(
            f"unknown exam requirement {requirement_id!r}; "
            f"declared: {[r.requirement_id for r in self.requirements]}"
        )

    def documentation_paths(self, project_root: str | Path) -> list[Path]:
        """Student documentation files the definition accepts (RQ-EXM-008)."""
        root = Path(project_root)
        found: list[Path] = []
        for pattern in self.documentation_rules.accepted_globs:
            found.extend(sorted(root.glob(pattern)))
        return found


class ExamEvent(BaseModel):
    """One application event on the authoritative exam attempt log."""

    event_id: str = Field(default_factory=lambda: URN.make("exam_event"))
    exam_attempt_id: str
    type: ExamEventType
    timestamp: datetime = Field(default_factory=Timestamps.now)
    question_id: str | None = None
    duration_ms: int | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def counts_toward_allowance(self) -> bool:
        return self.type in ASK_SUCCESS_EVENTS


class ExamAttempt(BaseModel):
    """One execution of one exam by one student (RQ-EXM-001, RQ-EXM-003)."""

    exam_attempt_id: str = Field(
        default_factory=lambda: URN.make("exam_attempt")
    )
    #: The five identities stay separate; none is derived from another.
    student_id: str
    project_id: str
    exam_id: str
    attempt_id: str | None = None
    exercise_id: str | None = None
    started_at: datetime = Field(default_factory=Timestamps.now)
    finished_at: datetime | None = None
    duration_seconds: int | None = None
    allowed_duration_seconds: int | None = None
    overtime_seconds: int | None = None
    allowed_ask_count: int | None = None
    ask_count: int = 0
    status: ExamStatus = ExamStatus.created
    event_ids: list[str] = Field(default_factory=list)
    rubric_ref: str = DEFAULT_EXAM_RUBRIC_REF
    docs_dir: str | None = None
    #: Locale snapshot captured at exam start (spec 0010, RQ-LNG-013). The
    #: finish report uses this locale even if the profile locale changes
    #: later. ``None`` on legacy records → deterministic fallback applies.
    locale: str | None = None
    #: The only field a completed attempt may still change (RQ-EXM-004).
    administrative_metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def is_active(self) -> bool:
        return self.status is ExamStatus.active

    @property
    def is_completed(self) -> bool:
        return self.status is ExamStatus.completed

    def substantive(self) -> dict[str, Any]:
        """Payload compared on save; excludes administrative metadata."""
        return {
            k: v
            for k, v in self.model_dump(mode="json").items()
            if k not in ADMINISTRATIVE_FIELDS
        }


